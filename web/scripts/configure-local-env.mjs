import { readFile, writeFile } from 'node:fs/promises'
import { fileURLToPath } from 'node:url'
import path from 'node:path'

const scriptDirectory = path.dirname(fileURLToPath(import.meta.url))
const webRoot = path.resolve(scriptDirectory, '..')
const sourcePath = path.resolve(webRoot, '..', '.generated', 'local-cognito.env')
const destinationPath = path.join(webRoot, '.env.local')
const clientIdKey = 'TRADE_LEDGER_LOCAL_COGNITO_CLIENT_ID'

let source

try {
  source = await readFile(sourcePath, 'utf8')
} catch (error) {
  if (error?.code === 'ENOENT') {
    throw new Error(
      `Missing ${path.relative(path.dirname(webRoot), sourcePath)}. Run deploy/scripts/bootstrap-all.sh first.`,
      { cause: error },
    )
  }
  throw error
}

const prefix = `export ${clientIdKey}=`
const line = source.split(/\r?\n/u).find((candidate) => candidate.startsWith(prefix))
const clientId = line?.slice(prefix.length).trim()

if (!clientId || !/^[A-Za-z0-9_-]+$/u.test(clientId)) {
  throw new Error(`Missing or invalid public ${clientIdKey} in the generated environment file.`)
}

await writeFile(
  destinationPath,
  `# Generated by npm run config:local. Do not commit.\nVITE_COGNITO_CLIENT_ID=${clientId}\nVITE_COGNITO_REGION=eu-west-2\n`,
  { encoding: 'utf8', mode: 0o600 },
)

console.log('Wrote .env.local with the public Cognito app-client identifier only.')
